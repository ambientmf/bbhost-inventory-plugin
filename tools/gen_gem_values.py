#!/usr/bin/env python3
"""Generates plugin/gem_values.h: every gem effect id with its value.

Source: Noxde/Bloodborne-save-editor, src-tauri/resources/upgrades.json
(GPL-3.0; https://github.com/Noxde/Bloodborne-save-editor). Each effect's
text ("Physical ATK UP +27.2%") gives its value; we keep |value| x 100.

Usage: gen_gem_values.py UPGRADES_JSON > plugin/gem_values.h
"""
import json
import re
import sys

NUMBER = re.compile(r"[-+]?\d+(?:\.\d+)?")


def main():
    effects = json.load(open(sys.argv[1]))["gemEffects"]
    rows = []
    for key, effect in effects.items():
        eid = int(key)
        m = NUMBER.search(effect["effect"])
        if eid == 0xFFFFFFFF or not m:
            continue
        rows.append((eid, round(abs(float(m.group())) * 100)))
    rows.sort()
    print("/* Generated by tools/gen_gem_values.py - do not edit.")
    print(" * Gem effect id -> |value| x 100, from Noxde/Bloodborne-save-editor's")
    print(" * resources/upgrades.json (GPL-3.0, https://github.com/Noxde/Bloodborne-save-editor). */")
    print("#ifndef GEM_VALUES_H")
    print("#define GEM_VALUES_H")
    print("#include <stdint.h>")
    print(f"#define GEM_VALUES_COUNT {len(rows)}")
    print("static const struct { uint32_t id; uint32_t value; } gem_values[GEM_VALUES_COUNT] = {")
    for i in range(0, len(rows), 6):
        print("    " + " ".join(f"{{{e}, {v}}}," for e, v in rows[i:i + 6]))
    print("};")
    print("#endif")


if __name__ == "__main__":
    main()
